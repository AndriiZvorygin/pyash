import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { buildProgram } from "../program/program.mjs";
import { encodePyacPack, lowerParagraph } from "../program/library/vliw/index.mjs";
import { minimumUniquePrefix, resolvePyashCommand } from "../command/pyash/command_names.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cliPath = path.join(repoRoot, "command/pyash.mjs");

function runCli(args) {
  return spawnSync(process.execPath, [cliPath, ...args], {
    cwd: repoRoot,
    encoding: "utf8",
    timeout: 30000
  });
}

async function withTempDirectory(run) {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "pyash-cli-extended-"));
  try {
    await run(directory);
  } finally {
    await fs.rm(directory, { recursive: true, force: true });
  }
}

function helloWorldPack() {
  const source = 'ob text "Hello, " be text ya\nob text "world!" be text ya\n';
  return encodePyacPack(lowerParagraph(buildProgram(source).sentences));
}

test("top-level commands resolve their shortest unique prefixes", () => {
  assert.equal(minimumUniquePrefix("verify"), "v");
  assert.equal(minimumUniquePrefix("channel"), "ch");
  assert.equal(minimumUniquePrefix("configure"), "con");
  assert.equal(minimumUniquePrefix("compile"), "com");
  assert.equal(minimumUniquePrefix("run"), "ru");
  assert.equal(minimumUniquePrefix("resume"), "res");
  assert.equal(minimumUniquePrefix("repl"), "rep");
  assert.equal(resolvePyashCommand("codex").command, "codex");
  assert.equal(resolvePyashCommand("sa").command, "saddle");
  assert.deepEqual(resolvePyashCommand("co").ambiguous, ["configure", "codex", "compile"]);
});

test("pyash translate decodes a PyAC pack to readable Pyash using from/to paths", async () => {
  await withTempDirectory(async (directory) => {
    const sourcePath = path.join(directory, "hello input.pyac");
    const outputPath = path.join(directory, "hello output.pya");
    await fs.writeFile(sourcePath, helloWorldPack());

    const result = runCli(["translate", "from", sourcePath, "to", outputPath]);
    assert.equal(result.status, 0, result.stderr);
    const output = await fs.readFile(outputPath, "utf8");
    const reparsed = buildProgram(output).sentences;
    assert.deepEqual(reparsed.map((sentence) => sentence.ob.text), ["Hello, ", "world!"]);
  });
});

test("pyash translate accepts its unique prefix and does not leave partial output on unsupported input", async () => {
  await withTempDirectory(async (directory) => {
    const sourcePath = path.join(directory, "invalid.pyac");
    const outputPath = path.join(directory, "invalid.pya");
    await fs.writeFile(sourcePath, encodePyacPack([new Array(16).fill(0xffff)]));

    const result = runCli(["t", "from", sourcePath, "to", outputPath]);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /PyAC codelet 1/);
    assert.equal(await fs.stat(outputPath).then(() => true, () => false), false);
  });
});

test("pyash compile infers C output for PyAC and accepts the shortest unique prefix", async () => {
  await withTempDirectory(async (directory) => {
    const sourcePath = path.join(directory, "hello.pyac");
    const outputPath = path.join(directory, "hello.c");
    await fs.writeFile(sourcePath, helloWorldPack());

    const result = runCli(["com", "from", sourcePath, "to", outputPath]);
    assert.equal(result.status, 0, result.stderr);
    assert.match(await fs.readFile(outputPath, "utf8"), /Generated by Pyash compile/);

    const assemblyPath = path.join(directory, "hello.asm");
    const assemblyResult = runCli(["compile", "from", sourcePath, "to", assemblyPath]);
    assert.equal(assemblyResult.status, 0, assemblyResult.stderr);
    assert.match(await fs.readFile(assemblyPath, "utf8"), /vliw_program:/);
  });
});

test("pyash compile infers JavaScript output for Pyash source", async () => {
  await withTempDirectory(async (directory) => {
    const sourcePath = path.join(directory, "source.pya");
    const outputPath = path.join(directory, "output.mjs");
    await fs.writeFile(sourcePath, 'ob text "compiled source" be write do\n', "utf8");

    const result = runCli(["compile", "from", sourcePath, "to", outputPath]);
    assert.equal(result.status, 0, result.stderr);
    assert.match(await fs.readFile(outputPath, "utf8"), /compiled source/);
  });
});

test("pyash dictionary forwards existing Kwon arguments", () => {
  const direct = spawnSync(process.execPath, [path.join(repoRoot, "command/vocab_suggest.mjs"), "love"], {
    cwd: repoRoot,
    encoding: "utf8",
    timeout: 30000
  });
  const routed = runCli(["d", "love"]);
  assert.equal(routed.status, direct.status, routed.stderr);
  assert.equal(routed.stdout, direct.stdout);
  assert.equal(routed.stderr, direct.stderr);
});

test("ambiguous prefixes report choices and direct Pyash file execution remains available", async () => {
  const ambiguous = runCli(["co"]);
  assert.equal(ambiguous.status, 2);
  assert.match(ambiguous.stderr, /configure, codex, compile/);

  await withTempDirectory(async (directory) => {
    const programPath = path.join(directory, "direct.pya");
    await fs.writeFile(programPath, 'ob text "direct file" be write do\n', "utf8");
    const direct = runCli([programPath]);
    assert.equal(direct.status, 0, direct.stderr);
    assert.match(direct.stdout, /direct file/);
  });
});

test("pyash help lists the new commands and shortest unique forms", () => {
  const result = runCli(["--help"]);
  assert.equal(result.status, 0);
  assert.match(result.stdout, /pyash compile from <source> to <destination>/);
  assert.match(result.stdout, /pyash translate from <source\.pyac> to <destination\.pya>/);
  assert.match(result.stdout, /pyash dictionary/);
  assert.match(result.stdout, /PyAC to \.c\/\.asm/);
  assert.match(result.stdout, /com=compile/);
  assert.match(result.stdout, /con=configure/);
  assert.match(result.stdout, /ch=channel/);
});
