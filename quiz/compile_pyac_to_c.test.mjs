import test from "node:test";
import assert from "node:assert/strict";
import os from "node:os";
import path from "node:path";
import fs from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

import { parse } from "../program/understand/index.mjs";
import { interpret } from "../program/bridge/index.mjs";
import { forget } from "../program/remember/index.mjs";
import {
  encodePyacPack,
  executeCodelets,
  lowerParagraph
} from "../program/library/vliw/index.mjs";

const execFileAsync = promisify(execFile);

async function withTempDirectory(run) {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "pyash-pyac-c-"));
  try {
    await run(directory);
  } finally {
    await fs.rm(directory, { recursive: true, force: true });
  }
}

test("compile persisted constant-arithmetic PyAC pack to C and run it", async () => {
  forget();

  const paragraph = [
    parse("ob num 1 to num 1 be plus do"),
    parse("ob num 9 from num 4 be subtract do"),
    parse("ob num 3 with num 4 be multiply do"),
    parse("ob num 5 with num 2 be divide do"),
    parse("ob num 7 to num 3 be xor do"),
    parse("ob num 2 from num 10 be exponential do"),
    parse("ob num 9 from num 4 be remains do"),
    parse("ob num 5 be invert do"),
    parse("ob num 65535 to num 1 be plus do"),
    parse("ob num 2 from num 9 be subtract do"),
    parse("ob num 2 from num 20 be exponential do")
  ];
  const codelets = lowerParagraph(paragraph);
  const expectedFacts = await executeCodelets(codelets);

  await withTempDirectory(async (directory) => {
    const packPath = path.join(directory, "program.pyac");
    const cPath = path.join(directory, "program.c");
    const executablePath = path.join(directory, "program");
    await fs.writeFile(packPath, encodePyacPack(codelets));

    const compileSentence = parse(
      `from filename "${packPath}" fromstate pyac tostate c to filename "${cPath}" be compile do`
    );
    await interpret(compileSentence);

    const cSource = await fs.readFile(cPath, "utf8");
    assert.match(cSource, /Generated by Pyash compile/);
    await execFileAsync("cc", ["-std=c11", "-Wall", "-Werror", "-o", executablePath, cPath], {
      timeout: 120000
    });

    const { stdout } = await execFileAsync(executablePath, [], { timeout: 120000 });
    assert.deepEqual(
      stdout.trim().split(/\r?\n/).map((line) => JSON.parse(line)),
      expectedFacts
    );
  });
});

