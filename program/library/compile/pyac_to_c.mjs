import { decodeCodelet } from "../vliw/index.mjs";
import { decodePyacPack } from "../vliw/database.mjs";

const SUPPORTED_SEMANTICS = new Set([
  "numeric-plus",
  "numeric-arithmetic",
  "numeric-invert"
]);

export class PyacCCompileError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = "PyacCCompileError";
    this.code = code;
    this.details = details;
  }
}

function fail(code, message, details = {}) {
  throw new PyacCCompileError(code, message, details);
}

function numericOperands(sentence, codeletIndex) {
  const left = sentence?.ob?.num;
  const right = sentence?.to?.num ?? sentence?.from?.num ?? sentence?.with?.num ?? sentence?.by?.num;
  if (!Number.isInteger(left) || left < 0 || left > 0xffff) {
    fail("invalid-numeric-codelet", `PyAC codelet ${codeletIndex} has an invalid left operand`, {
      codeletIndex,
      left
    });
  }
  if (!Number.isInteger(right) || right < 0 || right > 0xffff) {
    fail("invalid-numeric-codelet", `PyAC codelet ${codeletIndex} has an invalid right operand`, {
      codeletIndex,
      right
    });
  }
  return { left, right };
}

function lowerCodelet(decoded, codeletIndex) {
  if (!SUPPORTED_SEMANTICS.has(decoded.semantic)) {
    fail("unsupported-codelet", `PyAC codelet ${codeletIndex} cannot be compiled to C (${decoded.semantic})`, {
      codeletIndex,
      semantic: decoded.semantic
    });
  }

  const sentence = decoded.sentence;
  const resultName = `pya_result_${codeletIndex}`;
  if (decoded.semantic === "numeric-invert") {
    const value = sentence?.ob?.num;
    if (!Number.isInteger(value) || value < 0 || value > 0xffff) {
      fail("invalid-numeric-codelet", `PyAC codelet ${codeletIndex} has an invalid invert operand`, {
        codeletIndex,
        value
      });
    }
    return `  const int64_t ${resultName} = -(int64_t)${value};`;
  }

  const { left, right } = numericOperands(sentence, codeletIndex);
  let expression;
  switch (sentence.be) {
    case "plus":
      expression = `pya_vliw_add(${left}u, ${right}u)`;
      break;
    case "subtract":
      expression = `((${left}u > ${right}u) ? (int64_t)(${left}u - ${right}u) : 0)`;
      break;
    case "multiply":
      expression = `((int64_t)${left}u * (int64_t)${right}u)`;
      break;
    case "divide":
      expression = `pya_vliw_divide(${left}u, ${right}u)`;
      break;
    case "xor":
      expression = `((int64_t)((uint16_t)${left}u ^ (uint16_t)${right}u))`;
      break;
    case "exponential":
      expression = `pya_vliw_power(${left}u, ${right}u)`;
      break;
    case "remains":
      expression = `pya_vliw_remains(${left}u, ${right}u)`;
      break;
    default:
      fail("unsupported-codelet", `PyAC codelet ${codeletIndex} cannot be compiled to C (${sentence.be})`, {
        codeletIndex,
        semantic: decoded.semantic,
        verb: sentence.be
      });
  }
  return `  const int64_t ${resultName} = ${expression};`;
}

function cSourceFor(codelets) {
  const instructions = codelets.map((decoded, index) => lowerCodelet(decoded, index));
  const verbs = new Set(codelets.map((decoded) => decoded.sentence?.be));
  const outputs = codelets.map((_, index) => (
    `  if (printf("%lld\\n", (long long)pya_result_${index}) < 0) return 2;`
  ));
  const lines = [
    "/* Generated by Pyash compile from PyAC VLIW */",
    "#include <stdint.h>",
    "#include <stdio.h>",
    "#include <stdlib.h>",
  ];
  if (verbs.has("plus")) {
    lines.push(
      "",
      "static uint16_t pya_vliw_add(uint16_t left, uint16_t right) {",
      "  uint32_t sum = (uint32_t)left + (uint32_t)right;",
      "  return (uint16_t)(sum > UINT16_MAX ? UINT16_MAX : sum);",
      "}"
    );
  }
  if (verbs.has("divide")) {
    lines.push(
      "",
      "static int64_t pya_vliw_divide(uint16_t left, uint16_t right) {",
      "  if (right == 0) { fputs(\"division-by-zero\\n\", stderr); exit(1); }",
      "  return (int64_t)(left / right);",
      "}"
    );
  }
  if (verbs.has("remains")) {
    lines.push(
      "",
      "static int64_t pya_vliw_remains(uint16_t left, uint16_t right) {",
      "  if (right == 0) { fputs(\"division-by-zero\\n\", stderr); exit(1); }",
      "  return (int64_t)(left % right);",
      "}"
    );
  }
  if (verbs.has("exponential")) {
    lines.push(
      "",
      "static uint16_t pya_vliw_power(uint16_t base, uint16_t exponent) {",
      "  uint32_t value = 1;",
      "  for (uint16_t index = 0; index < exponent; index += 1) {",
      "    if (base != 0 && value > UINT16_MAX / base) return UINT16_MAX;",
      "    value *= base;",
      "  }",
      "  return (uint16_t)value;",
      "}"
    );
  }
  lines.push(
    "",
    "int main(void) {",
    ...instructions,
    ...outputs,
    "  return 0;",
    "}",
    ""
  );
  return lines.join("\n");
}

export function compilePyacPackToC(input) {
  let pack;
  try {
    pack = decodePyacPack(input);
  } catch (error) {
    fail(
      error?.code ?? "invalid-pyac-pack",
      `compile: invalid PyAC pack: ${error?.message ?? String(error)}`,
      { cause: error?.code ?? null, details: error?.details ?? null }
    );
  }

  const codelets = pack.codelets.map((words, index) => {
    try {
      return decodeCodelet(words);
    } catch (error) {
      fail(
        error?.code ?? "invalid-codelet",
        `compile: PyAC codelet ${index} is invalid: ${error?.message ?? String(error)}`,
        { codeletIndex: index, cause: error?.code ?? null, details: error?.details ?? null }
      );
    }
  });

  return cSourceFor(codelets);
}
